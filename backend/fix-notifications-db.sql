-- ============================================================================
--  تعمیر یک‌باره‌ی دیتابیس قدیمی برای «اعلان‌ها» — ای‌پلاک (ورامین)
--  فایل: backend/fix-notifications-db.sql
-- ============================================================================
--  چرا این فایل؟
--    دیتابیس بعضی هاست‌ها از نسخه‌ی قدیمی ساخته شده و جدول `notifications` آن:
--      ۱) ستون `send_id` ندارد،
--      ۲) کلید خارجی `user_phone → users(phone)` دارد (اعلان عمومی «all» و
--         کاربری که ردیف `users` ندارد رد می‌شوند)،
--      ۳) نویسه‌گانش `utf8` سه‌بایتی است (ایموجی عنوان/متن ذخیره نمی‌شود).
--    در آن حالت، پنل ادمین موقع ارسال اعلان این خطا را می‌داد:
--       SQLSTATE[42S22]: Column not found: 1054 Unknown column 'send_id'
--    و اپ «هیچ» اعلانی نشان نمی‌داد.
--
--    کدِ فعلی پروژه این سه مورد را در اولین اجرا «خودکار» ترمیم می‌کند و اگر
--    ترمیم ممکن نباشد هم اعلان‌ها را در حالت سازگار ذخیره/نمایش می‌دهد.
--    این فایل فقط برای وقتی است که:
--      • کاربر دیتابیس اجازه‌ی ALTER ندارد، یا
--      • می‌خواهید ترمیم «یک‌جا و قطعی» انجام شود (توصیه می‌شود).
--
--  چطور اجرا شود؟
--    phpMyAdmin → دیتابیس پروژه → سربرگ SQL → چسباندن محتوا → Go
--    (یا:  mysql -u USER -p DBNAME < backend/fix-notifications-db.sql )
--
--  ⚠️ هیچ داده‌ای پاک نمی‌شود؛ فقط «ساختار» جدول‌ها درست می‌شود.
--     با این حال، پیش از اجرا یک نسخه‌ی پشتیبان (Export) بگیرید.
--
--  نکته: دستورهای هر بخش «ترتیب» دارند. کلید خارجی باید «پیش از» تبدیل
--        نویسه‌گان حذف شود؛ وگرنه MySQL به‌خاطر تفاوت collation ستون‌های
--        کلید خارجی، خطای errno 150 می‌دهد.
-- ============================================================================


-- ────────────────────────────────────────────────────────────────────────────
-- ۱) ستون شناسه‌ی «ارسال گروهی»
--    با این ستون، اعلان‌های یک ارسالِ پنل به هم گره می‌خورند تا صفحه‌ی
--    «گیرندگان» و وضعیت خوانده‌شدنِ هر ارسال درست کار کند.
--    اگر پیام «Duplicate column name 'send_id'» دیدید یعنی ستون از قبل هست؛
--    اشکالی ندارد، همان بخش را رد کنید و ادامه دهید.
-- ────────────────────────────────────────────────────────────────────────────
ALTER TABLE `notifications`
  ADD COLUMN `send_id` INT NULL AFTER `read_flag`;


-- ────────────────────────────────────────────────────────────────────────────
-- ۲) نمایه (ایندکس) برای سرعت فهرست اعلان‌ها
--    اپ هر چند ثانیه فهرست اعلان‌های همان کاربر را می‌پرسد؛ بدون نمایه،
--    روی جدول بزرگ هر درخواست «جستجوی کامل» می‌شود.
--    اگر پیام Duplicate key name دیدید، یعنی نمایه هست → رد کنید.
-- ────────────────────────────────────────────────────────────────────────────
ALTER TABLE `notifications` ADD INDEX `idx_notifications_user_phone` (`user_phone`);
ALTER TABLE `notifications` ADD INDEX `idx_notifications_send_id` (`send_id`);


-- ────────────────────────────────────────────────────────────────────────────
-- ۳) حذف کلید خارجیِ مزاحم روی notifications.user_phone
--    این کلید خارجی باعث می‌شد:
--      • اعلان عمومی پنل (user_phone = 'all') با خطای ۲۳۰۰۰/۱۴۵۲ رد شود،
--      • اعلان کاربری که هنوز در جدول users ردیف ندارد ذخیره نشود.
--    «اعلان» ذاتاً می‌تواند برای «همه» باشد، پس این وابستگی درست نیست.
--
--    ابتدا نام دقیق کلید خارجی را در دیتابیس «خودتان» پیدا کنید (ممکن است با
--    نام پیش‌فرض یکی نباشد):
--
--      SELECT CONSTRAINT_NAME, TABLE_NAME, COLUMN_NAME
--        FROM information_schema.KEY_COLUMN_USAGE
--       WHERE TABLE_SCHEMA = DATABASE()
--         AND REFERENCED_TABLE_NAME IS NOT NULL
--         AND TABLE_NAME = 'notifications';
--
--    سپس همان نام را در دستور زیر بگذارید (نام پیش‌فرضِ mysqldump:
--    notifications_ibfk_1). اگر پرس‌وجوی بالا هیچ ردیفی نداد، یعنی کلید خارجی
--    وجود ندارد → این بخش را کامل رد کنید.
-- ────────────────────────────────────────────────────────────────────────────
ALTER TABLE `notifications` DROP FOREIGN KEY `notifications_ibfk_1`;


-- ────────────────────────────────────────────────────────────────────────────
-- ۴) نویسه‌گان utf8mb4 برای ذخیره‌ی ایموجی (✅ 📣 🔔)
--    با utf8 سه‌بایتی، درج عنوان ایموجی‌دار با «Incorrect string value» رد
--    می‌شد و در نتیجه «کل» اعلان از بین می‌رفت.
--    (کد فعلی در این حالت ایموجی را پیش از درج برمی‌دارد تا اعلان نپرد، ولی
--     با این تبدیل، ایموجی‌ها هم درست نمایش داده می‌شوند.)
-- ────────────────────────────────────────────────────────────────────────────
ALTER TABLE `notifications`
  CONVERT TO CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

ALTER TABLE `notification_sends`
  CONVERT TO CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;


